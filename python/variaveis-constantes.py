#variaveis e constantes
#variaveis são usadas para armazenar valores que podem ser alterados durante a execução do programa, enquanto constantes são usadas para armazenar valores que não devem ser alterados.


#Em Python, não existe uma sintaxe específica para declarar constantes, mas é uma convenção usar letras maiúsculas para indicar que uma variável é uma constante. Por exemplo:
PI = 3.14
GRAVIDADE = 9.81


#Em Python, as variáveis são criadas simplesmente atribuindo um valor a um nome de variável. Por exemplo:

#criando uma variável para armazenar o nome de uma pessoa
nome = "Maria"

#criando uma variável para armazenar a idade de uma pessoa
idade = 30


#criando uma variável para armazenar o preço de um produto
preco = 10.99
#criando uma variável para armazenar a altura de uma pessoa
altura = 1.75


#exemplo de uso de variáveis para calcular a área de um círculo
PI = 3.14
raio = 5
area = PI * raio**2
print(f"A área do círculo é {area}")


#converter inteiro para float
#Em Python, é possível converter um valor de um tipo para outro usando as funções de conversão. Para converter um inteiro para um float, você pode usar a função float(). Por exemplo:

#criando uma variável do tipo inteiro
preco = 10
print(preco)

#convertendo a variável para o tipo float
preco = float(preco)
print(preco)
