# Matriz é uma estrutura de dados bidimensional, ou seja, é uma coleção de elementos organizados em linhas e colunas. 
# Em Python, podemos representar uma matriz usando listas aninhadas (listas dentro de listas). Cada elemento da matriz pode ser acessado usando dois índices: o primeiro índice representa a linha e o segundo índice representa a coluna.
matriz = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]
print(matriz[0][0]) # Acessa 1a linha, 1o elemento = 1
print(matriz[1][2]) # Acessa 2a linha, 3o elemento = 6
print(matriz[2][1]) # Acessa 3a linha, 2o elemento = 8